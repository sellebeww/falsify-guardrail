#!/usr/bin/env bash
# Idempotent toolchain setup for Falsify (plan §5, §9).
# Installs: Python venv + pinned deps, Foundry (pinned), solc, Slither, Echidna (optional).
# Foundry installs to ~/.foundry (global, reversible: rm -rf ~/.foundry).
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"

SOLC_VERSION="${SOLC_VERSION:-0.8.24}"
FOUNDRY_VERSION="${FOUNDRY_VERSION:-1.8.3}"
ECHIDNA_VERSION="${ECHIDNA_VERSION:-2.3.3}"

echo "==> Python venv + pinned dev/analysis deps"
[ -d .venv ] || python3 -m venv .venv
./.venv/bin/python -m pip install --quiet --upgrade pip
./.venv/bin/python -m pip install --quiet -e ".[dev,analysis]"

echo "==> solc ${SOLC_VERSION} via solc-select"
./.venv/bin/solc-select install "${SOLC_VERSION}" 0.8.20
./.venv/bin/solc-select use "${SOLC_VERSION}"

echo "==> Foundry ${FOUNDRY_VERSION}"
if [ ! -x "${HOME}/.foundry/bin/foundryup" ]; then
  curl -fsSL https://foundry.paradigm.xyz | bash
fi
"${HOME}/.foundry/bin/foundryup" --install "${FOUNDRY_VERSION}"

echo "==> Echidna ${ECHIDNA_VERSION} (optional, property fuzzing)"
if ! command -v echidna >/dev/null 2>&1; then
  case "$(uname -s)" in
    Darwin)
      if command -v brew >/dev/null 2>&1; then
        HOMEBREW_NO_AUTO_UPDATE=1 brew install echidna || echo "   (echidna install failed; optional)"
      else
        echo "   (no Homebrew; skipping echidna)"
      fi
      ;;
    Linux)
      url="https://github.com/crytic/echidna/releases/download/v${ECHIDNA_VERSION}/echidna-${ECHIDNA_VERSION}-$(uname -m)-linux.tar.gz"
      curl -fsSL "$url" | tar -xz -C ./.venv/bin echidna || echo "   (echidna install failed; optional)"
      ;;
  esac
fi

echo "==> Recording versions.lock"
export PATH="${HOME}/.foundry/bin:${ROOT}/.venv/bin:${PATH}"
{
  echo "# Falsify toolchain lock — generated by scripts/bootstrap.sh"
  echo "python   = $(./.venv/bin/python --version 2>&1 | awk '{print $2}')"
  echo "forge    = $(forge --version 2>/dev/null | head -1)"
  echo "solc     = $(./.venv/bin/solc --version 2>/dev/null | tail -1)"
  echo "slither  = $(./.venv/bin/slither --version 2>&1 | tail -1)"
  echo "echidna  = $(echidna --version 2>/dev/null | head -1 || echo 'not installed (optional)')"
} > versions.lock
cat versions.lock

echo "==> Done. Try: make demo"
